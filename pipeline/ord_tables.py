def expand_shijing() -> list[tuple[int, str, str, str]]:
    """展开为 (ord, 门类, 分组, 篇名)，ord 从 1 开始。"""
    out = []
    n = 0
    for gate, group, names in SHIJING_GROUPS:
        for nm in names.split():
            n += 1
            out.append((n, gate, group, nm))
    return out


def expand_canon(name: str) -> list[tuple[int, str]]:
    return [(i + 1, v) for i, v in enumerate(CANON.get(name, []))]


